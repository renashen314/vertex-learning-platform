/**
 * The project's inline SVG set — 24×24 grid, 2px stroke, rounded caps, per the
 * design system's icon specs. Inline rather than an icon package so the stroke
 * inherits `currentColor` and nothing ships to the browser but the path data.
 *
 * Every icon takes a `size` so callers keep the exact pixel dimensions the
 * design asks for.
 */

export interface IconProps {
  size?: number;
  className?: string;
}

function svgProps(size: number) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
  };
}

